import { access, cp, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, "..");
const sourceDir = path.join(rootDir, "assets");
const targetDir = path.join(rootDir, "public", "assets");
const markerPath = path.join(targetDir, ".synced-from-root-assets");

try {
  await access(sourceDir);
} catch {
  console.log("[sync-assets] Skipped: ./assets does not exist");
  process.exit(0);
}

await rm(targetDir, { recursive: true, force: true });
await mkdir(path.dirname(targetDir), { recursive: true });

await cp(sourceDir, targetDir, {
  recursive: true,
  force: true,
  filter: (sourcePath) => path.basename(sourcePath) !== ".DS_Store",
});
await writeFile(markerPath, "generated by scripts/sync-assets-to-public.mjs\n");

console.log("[sync-assets] Synced ./assets -> ./public/assets");
